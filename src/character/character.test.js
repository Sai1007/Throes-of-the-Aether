const assert=require('node:assert/strict');
const C=require('./character.js');
const a=C.createCharacter('player1');
assert.equal(a.pointsRemaining,20);
for(let i=0;i<5;i++)assert.equal(C.increaseStat(a,'HP'),true);
assert.equal(a.stats.HP,125);
assert.equal(C.increaseStat(a,'HP'),false);
for(let i=0;i<7;i++)assert.equal(C.increaseStat(a,'STA'),true);
assert.equal(a.stats.STA,24);
assert.equal(C.increaseStat(a,'STA'),false);
assert.equal(C.decreaseStat(a,'STA'),true);
assert.equal(a.stats.STA,22);
assert.equal(a.pointsRemaining,9);
assert.equal(C.resetCharacter(a),true);
assert.equal(a.pointsRemaining,20);
assert.equal(a.stats.HP,100);
assert.equal(C.selectColor(a,'Yellow'),true);
assert.equal(C.selectWeapon(a,'Staff'),true);
assert.equal(C.selectElement(a,'Aether'),true);
assert.equal(C.setCharacterName(a,'Knight'),true);
